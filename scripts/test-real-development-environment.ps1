        action = "native_build"; root = $nativeRoot; buildDir = (Join-Path $nativeRoot "build")
        configuration = "Release"; target = "AcceptanceNative"
    })
    [void](Invoke-TaskStep "native-test" "windows_development" @{
        action = "native_test"; root = $nativeRoot; buildDir = (Join-Path $nativeRoot "build"); configuration = "Release"
    })
    [void](Invoke-TaskStep "native-package" "windows_development" @{
        action = "native_package"; root = $nativeRoot; buildDir = (Join-Path $nativeRoot "build"); configuration = "Release"
    })

    [void](Invoke-TaskStep "electron-install" "windows_development" @{ action = "electron_install"; root = $electronRoot })
    [void](Invoke-TaskStep "electron-test" "windows_development" @{
        action = "electron_test"; root = $electronRoot; scriptName = "test"
    })
    [void](Invoke-TaskStep "electron-package" "windows_development" @{
        action = "electron_package"; root = $electronRoot; scriptName = "package"
    })

    $inspection = Invoke-McpTool "inspect_development_environment" @{ targets = @("dotnet", "native", "electron") }
    $requiredInspection = @(
        "microsoft.visualstudio.2022.buildtools",
        "microsoft.visualstudio.workload.manageddesktop",
        "microsoft.visualstudio.workload.nativedesktop"
    )
    foreach ($componentId in $requiredInspection) {
        if (@($inspection.components | Where-Object { $_.componentId -eq $componentId }).Count -ne 1) {
            throw "Windows workload inspection omitted a required reviewed component."
        }
    }
    Add-StepResult "windows-workload-inspection" "passed" 0 "reviewed-components-present"

    $runnable = Get-FirstArtifactPath $publish ".exe"
    $runTask = Start-LongTask "windows-run-artifact" "windows_development" @{
        action = "run"; artifactPath = $runnable; cwd = (Split-Path -Parent $runnable)
    } 120
    Stop-TaskOwnedArtifact $runTask "windows-stop-artifact"

    $missingCredential = Invoke-McpToolRaw "windows_development" @{
        action = "sign"; inFile = $runnable; outFile = (Join-Path $windowsRoot "missing-credential.exe")
        credentialId = "00000000-0000-4000-8000-000000000000"; timestampOrigin = "http://timestamp.digicert.com"
    }
    $missingBody = [string]$missingCredential.content[0].text | ConvertFrom-Json
    if ($missingBody.ok -ne $false -or $missingBody.code -ne "WINDOWS_CREDENTIAL_UNKNOWN") {
        throw "Windows missing-credential behavior was not enforced."
    }
    Add-StepResult "windows-missing-credential" "passed" 0 "stable-error"

    $windowsCredential = [Environment]::GetEnvironmentVariable("FEISHU_MCP_ACCEPTANCE_WINDOWS_CREDENTIAL_ID", "Process")
    $timestampOrigin = [Environment]::GetEnvironmentVariable("FEISHU_MCP_ACCEPTANCE_WINDOWS_TIMESTAMP_ORIGIN", "Process")
    if ([string]::IsNullOrWhiteSpace($windowsCredential) -or [string]::IsNullOrWhiteSpace($timestampOrigin)) {
        throw "Windows acceptance credential references are incomplete."
    }
    $signed = Join-Path $windowsRoot "acceptance-signed.exe"
    [void](Invoke-TaskStep "windows-sign" "windows_development" @{
        action = "sign"; inFile = $runnable; outFile = $signed
        credentialId = $windowsCredential; timestampOrigin = $timestampOrigin
    })
    [void](Invoke-TaskStep "windows-verify" "windows_development" @{ action = "verify"; inFile = $signed })
}

function Write-RedactedSummary([string]$FinalState) {
    $summary = [pscustomobject]@{
        mode = $Mode
        state = $FinalState
        stepCount = $script:Steps.Count
        totalDurationMs = [int64](($script:Steps | Measure-Object -Property durationMs -Sum).Sum)
        steps = @($script:Steps)
    }
    # The summary contains no paths, owner id, raw task ids, device serial,
    # credential ids, or secrets. In real mode it is written only inside the
    # marked disposable root, then emitted before confined cleanup.
    $json = $summary | ConvertTo-Json -Depth 8
    if ($script:CreatedRoot) {
        [System.IO.File]::WriteAllText((Join-Path $script:RootFullPath "reports\acceptance-summary.json"), $json)
    }
    Write-Output $json
}

$failed = $false
try {
    if ($Mode -eq "Inspect") {
        Run-InspectAcceptance
    } else {
        Initialize-DisposableRoot
        [void](Initialize-AcceptanceClient)
        if ($Mode -in @("Android", "All")) { Run-AndroidAcceptance }
        if ($Mode -in @("Windows", "All")) { Run-WindowsAcceptance }
    }
    Write-RedactedSummary "passed"
} catch {
    $failed = $true
    Add-StepResult $script:CurrentStep "failed" 0 "redacted-error"
    Write-RedactedSummary "failed"
    Write-Error "Acceptance failed at a redacted step. Review the local server/task logs."
} finally {
    if ($script:LongRunningTasks.Count -gt 0) {
        Stop-RemainingLongTasks
    }
    if ($Mode -ne "Inspect" -and $script:CreatedRoot) {
        Remove-DisposableRoot
    }
}

if ($failed) { exit 1 }
